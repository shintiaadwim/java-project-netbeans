    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        try {
            // 1. Ambil semua data dari text field
            String noPelanggan = No.getText();
            String nama = Nama.getText();
            String telp = Telp.getText();
            String alamat = Alamat.getText();
            
            // 2. Validasi sederhana (pastikan tidak kosong)
            if (noPelanggan.isEmpty() || nama.isEmpty() || telp.isEmpty() || alamat.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Semua data harus diisi!", "Error", JOptionPane.ERROR_MESSAGE);
                return; // Hentikan eksekusi
            }
            
            Pelanggan pelangganBaru;
            // 3. Buat objek Pelanggan baru
            // (Pastikan constructor di kelas Pelanggan sesuai urutan ini)
            if("Reguler".equals(cmbTipeLayananP.getSelectedItem().toString())) {
                pelangganBaru = new Pelanggan(noPelanggan, nama, telp, alamat);
            } else {
                double disc = Double.parseDouble(Diskon.getText());
                pelangganBaru = new PelangganVIP(noPelanggan, nama, telp, alamat);
                pelangganBaru.setDiskon(disc);
            }

            // 4. Tambahkan pelanggan baru ke SistemLaundry
            // (Saya asumsikan kamu punya method tambahPelanggan di SistemLaundry
            // yang menerima objek Pelanggan)
            sistem.tambahData(pelangganBaru); // Jika nama methodnya 'tambahData', ganti jadi sistem.tambahData(pelangganBaru)

            // 5. Beri pesan sukses
            JOptionPane.showMessageDialog(this, "Data pelanggan berhasil ditambahkan!");

            // 6. Kosongkan kembali field setelah berhasil
            No.setText("");
            Nama.setText("");
            Telp.setText("");
            Alamat.setText("");
            Diskon.setText("");

        } catch (Exception e) {
            // Tangani jika ada error lain
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        try {
            // 1. Ambil ID (No Pelanggan) dari text field
            String noPelanggan = No.getText();

            // 2. Validasi (pastikan ID diisi)
            if (noPelanggan.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Masukkan No Pelanggan yang akan dihapus!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 3. Panggil method hapus dari SistemLaundry
            // (Saya asumsikan kamu punya method hapusPelanggan berdasarkan ID string)
            boolean berhasilDihapus = sistem.hapusData(noPelanggan); // Jika nama methodnya 'hapusData', ganti jadi sistem.hapusData(noPelanggan)

            // 4. Beri feedback berdasarkan hasil
            if (berhasilDihapus) {
                JOptionPane.showMessageDialog(this, "Data pelanggan berhasil dihapus!");
                No.setText(""); // Kosongkan field ID
                Nama.setText("");
                Telp.setText("");
                Alamat.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Data pelanggan dengan No " + noPelanggan + " tidak ditemukan!", "Gagal Hapus", JOptionPane.WARNING_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnTambahLayananActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahLayananActionPerformed
        try {
            // 1. Ambil data umum
            String tipe = cmbTipeLayanan.getSelectedItem().toString();
            String kode = Kode.getText();
            String nama = NamaLayanan.getText();
            // Konversi String ke double/int
            double harga = Double.parseDouble(Harga.getText()); 
            int durasi = Integer.parseInt(cmbDurasi.getSelectedItem().toString()); // Asumsi cmbDurasi berisi angka

            // 2. Buat objek berdasarkan tipe (Polimorfisme)
            Layanan layananBaru; // Deklarasikan sebagai tipe parent (Layanan)

            if (tipe.equals("Reguler")) {
                // Validasi data umum
                if (kode.isEmpty() || nama.isEmpty()) throw new Exception("Data umum tidak boleh kosong!");

                layananBaru = new Layanan(kode, nama, harga, durasi);

            } else if (tipe.equals("Express")) {
                // Ambil data spesifik Express
                double tambahHarga = Double.parseDouble(TambahHarga.getText());

                layananBaru = new LayananExpress(kode, nama, harga, durasi, tambahHarga); // Sesuaikan constructor

            } else if (tipe.equals("Setrika")) {
                // Ambil data spesifik Setrika
                String jenisCucian = JenisCucianSetrika.getText(); 

                layananBaru = new LayananSetrika(kode, nama, harga, durasi, jenisCucian); // Sesuaikan constructor

            } else {
                throw new Exception("Tipe layanan tidak valid!");
            }

            // 3. Tambahkan objek ke SistemLaundry
            // (Asumsi kamu punya method 'tambahLayanan' di SistemLaundry)
            sistem.tambahData(layananBaru); // Ini bisa menerima Layanan, LayananExpress, & LayananSetrika

            // 4. Feedback dan bersihkan form
            JOptionPane.showMessageDialog(this, "Layanan " + nama + " berhasil ditambahkan!");
            bersihkanFormLayanan(); // Buat method helper untuk membersihkan field

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga/Durasi harus berupa angka!", "Error Input", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menambahkan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnTambahLayananActionPerformed

    // Method untuk mengisi ulang ComboBox dengan data terbaru
    private void refreshComboData() {
        // 1. Kosongkan dulu agar tidak duplikat
        cmbDaftarPelanggan.removeAllItems();
        cmbDaftarLayanan.removeAllItems();

        // 2. Isi ComboBox Pelanggan dari list di SistemLaundry
        // Asumsi: sistem.getPelangganList() mengembalikan ArrayList<Pelanggan>
        for (Pelanggan p : sistem.getPelangganList()) {
            // Menampilkan nama pelanggan di dropdown
            cmbDaftarPelanggan.addItem(p);
        }

        // 3. Isi ComboBox Layanan
        // Asumsi: sistem.getLayananList() mengembalikan ArrayList<Layanan>
        for (Layanan l : sistem.getLayananList()) {
            // Menampilkan nama layanan di dropdown
            cmbDaftarLayanan.addItem(l);
        }
    }
    
