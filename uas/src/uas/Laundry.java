    private void btnTambahLayananActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahLayananActionPerformed
        try {
            // 1. Ambil data umum
            String tipe = cmbTipeLayanan.getSelectedItem().toString();
            String kode = Kode.getText();
            String nama = Nama.getText();
            // Konversi String ke double/int
            double harga = Double.parseDouble(Harga.getText()); 
            int durasi = Integer.parseInt(cmbDurasi.getSelectedItem().toString()); // Asumsi cmbDurasi berisi angka

            // 2. Buat objek berdasarkan tipe (Polimorfisme)
            Layanan layananBaru; // Deklarasikan sebagai tipe parent (Layanan)

            if (tipe.equals("Reguler")) {
                // Validasi data umum
                if (kode.isEmpty() || nama.isEmpty()) throw new Exception("Data umum tidak boleh kosong!");

                layananBaru = new Layanan(kode, nama, harga, durasi);

            } else if (tipe.equals("Express")) {
                // Ambil data spesifik Express
                double tambahHarga = Double.parseDouble(TambahHarga.getText());

                layananBaru = new LayananExpress(kode, nama, harga, durasi, tambahHarga); // Sesuaikan constructor

            } else if (tipe.equals("Setrika")) {
                // Ambil data spesifik Setrika
                String jenisCucian = JenisCucianSetrika.getText(); 

                layananBaru = new LayananSetrika(kode, nama, harga, durasi, jenisCucian); // Sesuaikan constructor

            } else {
                throw new Exception("Tipe layanan tidak valid!");
            }

            // 3. Tambahkan objek ke SistemLaundry
            // (Asumsi kamu punya method 'tambahLayanan' di SistemLaundry)
            sistem.tambahData(layananBaru); // Ini bisa menerima Layanan, LayananExpress, & LayananSetrika

            // 4. Feedback dan bersihkan form
            JOptionPane.showMessageDialog(this, "Layanan " + nama + " berhasil ditambahkan!");
            bersihkanFormLayanan(); // Buat method helper untuk membersihkan field

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Harga/Durasi harus berupa angka!", "Error Input", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menambahkan: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnTambahLayananActionPerformed

